from newco_data import mk, std


def _m(name, year, desc, people, invs, note):
    N = [{'id': 'co', 'name': name, 'kind': 'c', 'from': year, 'desc': desc}]
    EN = {}
    for i, (nm, role, d, fr, founder, en) in enumerate(people, 1):
        n = {'id': 'p%d' % i, 'name': nm, 'kind': 'p', 'from': fr or year, 'desc': d, 'role': role}
        if founder:
            n['founder'] = 1
        N.append(n)
        if en:
            EN['p%d' % i] = en
    for i, row in enumerate(invs, 1):
        nm, role, d, fr = row[:4]
        n = {'id': 'v%d' % i, 'name': nm, 'kind': 'i', 'from': fr or year, 'desc': d, 'role': role}
        if len(row) > 4 and row[4]:
            n['to'] = row[4]
        N.append(n)
    from yen import yenify
    for _n in N:
        for _f in ('desc', 'role'):
            if _n.get(_f):
                _n[_f] = yenify(_n[_f])
    return mk(N, std('co'), EN, {}, {}, {}, {}, {}, 'co'), yenify(note)


